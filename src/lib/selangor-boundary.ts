/** Bounding box Selangor sebagai [[south, west], [north, east]]. */
export const selangorBounds: [[number, number], [number, number]] = [[2.5946, 100.8096], [3.8702, 101.9712]];

/** true jika titik berada dalam sempadan Selangor (lubang dikira sebagai luar). */
export function pointInSelangor(lat: number, lng: number): boolean {
  const inRing = (r: Ring) => {
    let c = false;
    for (let i = 0; i < r.length - 1; i++) {
      const a = r[i]; const b = r[i + 1];
      if (!a || !b) continue;
      const [y1, x1] = a; const [y2, x2] = b;
      if (y1 > lat !== y2 > lat) {
        const xt = x1 + ((lat - y1) * (x2 - x1)) / (y2 - y1);
        if (lng < xt) c = !c;
      }
    }
    return c;
  };
  for (const p of selangorParts) {
    const outer = p[0];
    if (!outer || !inRing(outer)) continue;
    let hole = false;
    for (let i = 1; i < p.length; i++) { const h = p[i]; if (h && inRing(h)) { hole = true; break; } }
    if (!hole) return true;
  }
  return false;
}
